const (
	// Dovecot only listens on loopback; the LAN-facing ports are forwarded to
	// it with a PROXY protocol header so it still sees the real client address.
	dovecotIMAPAddr  = "127.0.0.1:2143"
	dovecotIMAPSAddr = "127.0.0.1:2993"

	dovecotBin  = "dovecot"
	doveadmBin  = "doveadm"
	dovecotIMAP = "/usr/lib/dovecot/imap"
)

// Dovecot runs the optional Dovecot IMAP server that mail clients talk to in
// "Dovecot mode". It runs as the same unprivileged user as everything else.
type Dovecot struct {
	cfg        Config
	certs      *CertStore
	dir        string // generated configuration
	confPath   string
	passwdPath string
	baseDir    string // runtime sockets, must be a short path
}

func NewDovecot(cfg Config, certs *CertStore) *Dovecot {
	dir := filepath.Join(cfg.DataDir, "dovecot")
	return &Dovecot{
		cfg:        cfg,
		certs:      certs,
		dir:        dir,
		confPath:   filepath.Join(dir, "dovecot.conf"),
		passwdPath: filepath.Join(dir, "passwd"),
		baseDir:    filepath.Join(os.TempDir(), "mailbridge-dovecot"),
	}
}

// Home is the directory holding one login's mail, search index and sync state.
func (d *Dovecot) Home(login string) string {
	return filepath.Join(d.cfg.MailDir, strings.ToLower(login))
}

// Prepare writes the Dovecot configuration.
func (d *Dovecot) Prepare() error {
	me, err := user.Current()
	if err != nil {
		return fmt.Errorf("Dovecot mode needs the container user to exist in /etc/passwd (do not combine it with --user): %w", err)
	}
	group, err := user.LookupGroupId(me.Gid)
	if err != nil {
		return fmt.Errorf("Dovecot mode needs the container group to exist in /etc/group: %w", err)
	}

	certPath, keyPath := d.certs.Paths()

	for _, dir := range []string{d.dir, filepath.Join(d.dir, "state"), d.cfg.MailDir} {
		if err := os.MkdirAll(dir, 0o700); err != nil {
			return err
		}
	}
	if _, err := os.Stat(d.passwdPath); errors.Is(err, os.ErrNotExist) {
		if err := os.WriteFile(d.passwdPath, nil, 0o600); err != nil {
			return err
		}
	}

	imapsPort := "0"
	if len(d.cfg.IMAPSListen) > 0 {
		_, imapsPort, _ = strings.Cut(dovecotIMAPSAddr, ":")
	}
	_, imapPort, _ := strings.Cut(dovecotIMAPAddr, ":")

	conf := fmt.Sprintf(`# Generated by mailbridge at start-up. Changes are overwritten.
protocols = imap
listen = 127.0.0.1
base_dir = %[1]s
state_dir = %[2]s
instance_name = mailbridge
default_internal_user = %[3]s
default_internal_group = %[4]s
default_login_user = %[3]s
log_path = /dev/stderr
auth_verbose = yes

ssl = required
ssl_cert = <%[5]s
ssl_key = <%[6]s
ssl_min_protocol = TLSv1.2
disable_plaintext_auth = yes
auth_mechanisms = plain login
auth_username_format = %%Lu
haproxy_trusted_networks = 127.0.0.1/32

first_valid_uid = %[7]s
last_valid_uid = %[7]s
first_valid_gid = %[8]s
last_valid_gid = %[8]s
mail_location = maildir:~/Maildir:LAYOUT=fs:INDEX=~/index
mail_plugins = fts fts_xapian

passdb {
  driver = passwd-file
  args = scheme=SSHA512 username_format=%%Lu %[9]s
}
userdb {
  driver = static
  args = uid=%[7]s gid=%[8]s home=%[10]s/%%Lu
}

# Same hierarchy separator and folder names as Proton Mail Bridge.
namespace inbox {
  inbox = yes
  separator = /
  mailbox Drafts {
    special_use = \Drafts
  }
  mailbox Sent {
    special_use = \Sent
  }
  mailbox Trash {
    special_use = \Trash
  }
  mailbox Spam {
    special_use = \Junk
  }
  mailbox Archive {
    special_use = \Archive
  }
}

# Full-text search: indexed, MIME-decoded, kept up to date as mail arrives.
plugin {
  fts = xapian
  fts_xapian = partial=3 full=20
  fts_autoindex = yes
  fts_enforced = yes
  fts_autoindex_exclude = \Junk
}

service imap-login {
  chroot =
  inet_listener imap {
    address = 127.0.0.1
    port = %[11]s
    haproxy = yes
  }
  inet_listener imaps {
    address = 127.0.0.1
    port = %[12]s
    ssl = yes
    haproxy = yes
  }
}
service anvil {
  chroot =
}
service auth {
  user = $default_internal_user
}
service auth-worker {
  user = $default_internal_user
}
service indexer-worker {
  vsz_limit = 2G
}
`, d.baseDir, filepath.Join(d.dir, "state"), me.Username, group.Name, certPath, keyPath,
		me.Uid, me.Gid, d.passwdPath, d.cfg.MailDir, imapPort, imapsPort)

	return os.WriteFile(d.confPath, []byte(conf), 0o600)
}

// Run keeps Dovecot running until ctx is cancelled.
func (d *Dovecot) Run(ctx context.Context) {
	for ctx.Err() == nil {
		// Only this process ever starts Dovecot here, so anything left in the
		// runtime directory is from a killed container.
		_ = os.RemoveAll(d.baseDir)

		cmd := exec.Command(dovecotBin, "-F", "-c", d.confPath) // #nosec G204
		pr, pw := io.Pipe()
		cmd.Stdout, cmd.Stderr = pw, pw
		go func() {
			scanner := bufio.NewScanner(pr)
			for scanner.Scan() {
				fmt.Fprintln(os.Stdout, "[dovecot] "+scanner.Text())
			}
		}()

		log.Print("starting Dovecot")
		if err := cmd.Start(); err != nil {
			_ = pw.Close()
			log.Printf("cannot start Dovecot: %v; retrying in 10s", err)
			select {
			case <-ctx.Done():
			case <-time.After(10 * time.Second):
			}
			continue
		}

		exited := make(chan error, 1)
		go func() {
			exited <- cmd.Wait()
			_ = pw.Close()
		}()

		select {
		case err := <-exited:
			log.Printf("Dovecot exited (%v); restarting in 3s", err)
			select {
			case <-ctx.Done():
			case <-time.After(3 * time.Second):
			}
		case <-ctx.Done():
			_ = cmd.Process.Signal(syscall.SIGTERM)
			select {
			case <-exited:
			case <-time.After(15 * time.Second):
				_ = cmd.Process.Kill()
				<-exited
			}
		}
	}
}

// ssha512 hashes a password in Dovecot's SSHA512 scheme.
func ssha512(password string) string {
	salt := make([]byte, 16)
	if _, err := rand.Read(salt); err != nil {
		panic(err)
	}
	sum := sha512.Sum512(append([]byte(password), salt...))
	return "{SSHA512}" + base64.StdEncoding.EncodeToString(append(sum[:], salt...))
}

// WritePasswd replaces the list of logins Dovecot accepts. Dovecot notices the
// changed file by itself.
func (d *Dovecot) WritePasswd(accounts []MailAccount) error {
	var buf bytes.Buffer
	for _, a := range accounts {
		fmt.Fprintf(&buf, "%s:%s\n", strings.ToLower(a.Login), ssha512(a.Password))
	}
	tmp := d.passwdPath + ".tmp"
	if err := os.WriteFile(tmp, buf.Bytes(), 0o600); err != nil {
		return err
	}
	return os.Rename(tmp, d.passwdPath)
}

// boxStatus is what the sync engine needs to know about one Dovecot mailbox.
type boxStatus struct {
	Messages int
	Sig      string // changes whenever anything in the mailbox changes
}

// Status lists a login's mailboxes. It reads Dovecot's indexes, so it is cheap
// enough to call every few seconds.
func (d *Dovecot) Status(ctx context.Context, login string) (map[string]boxStatus, error) {
	out, err := d.doveadm(ctx, "-f", "tab", "mailbox", "status", "-u", login,
		"messages uidnext uidvalidity highestmodseq", "*")
	if err != nil {
		return nil, err
	}

	boxes := map[string]boxStatus{}
	lines := strings.Split(strings.TrimRight(string(out), "\n"), "\n")
	if len(lines) == 0 || lines[0] == "" {
		return boxes, nil
	}
	header := strings.Split(lines[0], "\t")
	col := map[string]int{}
	for i, h := range header {
		col[h] = i
	}
	for _, need := range []string{"mailbox", "messages"} {
		if _, ok := col[need]; !ok {
			return nil, fmt.Errorf("unexpected doveadm output: %q", lines[0])
		}
	}
	for _, line := range lines[1:] {
		f := strings.Split(line, "\t")
		if len(f) != len(header) {
			continue
		}
		n, _ := strconv.Atoi(f[col["messages"]])
		boxes[f[col["mailbox"]]] = boxStatus{Messages: n, Sig: strings.Join(f[1:], "/")}
	}
	return boxes, nil
}

// doveadm runs one doveadm command for a login and returns its output.
func (d *Dovecot) doveadm(ctx context.Context, args ...string) ([]byte, error) {
	ctx, cancel := context.WithTimeout(ctx, time.Minute)
	defer cancel()

	// #nosec G204 -- logins are validated by validLogin before any worker starts.
	cmd := exec.CommandContext(ctx, doveadmBin, append([]string{"-c", d.confPath}, args...)...)
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	out, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("doveadm %s: %v: %s", args[0], err, strings.TrimSpace(stderr.String()))
	}
	return out, nil
}

// Flagged counts, per mailbox, the messages flagged \Deleted but not expunged yet.
func (d *Dovecot) Flagged(ctx context.Context, login string) (map[string]int, error) {
	out, err := d.doveadm(ctx, "-f", "tab", "fetch", "-u", login, "mailbox", "deleted")
	if err != nil {
		return nil, err
	}
	counts := map[string]int{}
	lines := strings.Split(strings.TrimRight(string(out), "\n"), "\n")
	for i, line := range lines {
		if i > 0 && line != "" { // the first line is the column header
			counts[line]++
		}
	}
	return counts, nil
}

// Subscribe subscribes the login to mailboxes.
func (d *Dovecot) Subscribe(ctx context.Context, login string, boxes []string) error {
	_, err := d.doveadm(ctx, append([]string{"mailbox", "subscribe", "-u", login}, boxes...)...)
	return err
}

// Reload makes Dovecot read its configuration, and with it the certificate,
// again. Sessions that are open carry on.
func (d *Dovecot) Reload(ctx context.Context) {
	// Dovecot may be on its way up, with the old certificate read already
	// and not ready to be told yet. When it is down, its next start reads
	// the new one anyway.
	var err error
	for try := 0; try < 5; try++ {
		if _, err = d.doveadm(ctx, "reload"); err == nil {
			return
		}
		select {
		case <-ctx.Done():
			return
		case <-time.After(2 * time.Second):
		}
	}
	log.Printf("Dovecot did not pick up the new certificate, it will at its next start: %v", err)
}

// Kick disconnects the mail clients of a login.
func (d *Dovecot) Kick(ctx context.Context, login string) {
	// doveadm reports failure when nobody was connected; that is fine.
	_, _ = d.doveadm(ctx, "kick", login)
}
